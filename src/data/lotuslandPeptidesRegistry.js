/**
 * Deterministic helper to retrieve a Lotusland peptide by slug or alias,
 * ensuring public monograph pages (/p/[slug]) and batch QR pages can always resolve.
 */
export function getLotuslandPeptideBySlug(rawSlug) {
  if (!rawSlug) return null;
  const clean = String(rawSlug).toLowerCase().trim().replace(/^supplier[-_]/, '');
  
  // 1. Direct match by slug or id
  const direct = LOTUSLAND_PEPTIDES.find(p => p.slug === clean || p.id === clean);
  if (direct) {
    return {
      ...direct,
      variants: direct.variants || [
        {
          id: `var-${direct.slug}-${(direct.dosage || '10mg').replace(/\s+/g, '')}`,
          name: `${direct.canonicalName} ${direct.dosage}`,
          dose: direct.dosage,
          dosage: direct.dosage,
          strength: direct.dosage,
          format: 'vial',
          presentation: direct.presentation || '10R Borosilicate Lyophilized Vial',
          supplierId: 'supplier-lotusland',
          supplierName: 'Lotusland',
          purity: direct.purity,
          stock: direct.stock,
          status: 'published',
          isActive: true
        }
      ]
    };
  }

  // 2. Prefix or alias match
  const aliasMatch = LOTUSLAND_PEPTIDES.find(p => {
    const s = p.slug.toLowerCase();
    const c = p.canonicalName.toLowerCase();
    return clean === s || clean === c || clean.startsWith(s) || s.startsWith(clean);
  });

  if (aliasMatch) {
    return {
      ...aliasMatch,
      variants: aliasMatch.variants || [
        {
          id: `var-${aliasMatch.slug}-${(aliasMatch.dosage || '10mg').replace(/\s+/g, '')}`,
          name: `${aliasMatch.canonicalName} ${aliasMatch.dosage}`,
          dose: aliasMatch.dosage,
          dosage: aliasMatch.dosage,
          strength: aliasMatch.dosage,
          format: 'vial',
          presentation: aliasMatch.presentation || '10R Borosilicate Lyophilized Vial',
          supplierId: 'supplier-lotusland',
          supplierName: 'Lotusland',
          purity: aliasMatch.purity,
          stock: aliasMatch.stock,
          status: 'published',
          isActive: true
        }
      ]
    };
  }

  return null;
}
