/**
 * Resolves curated PubMed studies for any peptide/compound name.
 * Returns null if no curated entry matches (caller can fall back to live PubMed E-utilities).
 */
export function getCuratedClinicalEvidence(compoundName) {
  if (!compoundName) return null;
  const lower = String(compoundName).toLowerCase();
  for (const [key, studies] of Object.entries(PEPTIDE_CLINICAL_EVIDENCE)) {
    if (lower.includes(key)) {
      return studies;
    }
  }
  return null;
}
