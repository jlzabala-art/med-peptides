/**
 * Resolves the authoritative clinical monograph for any aesthetic injectable
 * by slug, product.id, or product.canonicalKey, merging cleanly with any
 * Firestore product fields.
 */
export function getInjectableMonograph(slug, product = {}) {
  const candidates = [
    slug,
    product?.slug,
    product?.id,
    product?.canonicalKey,
  ]
    .filter(Boolean)
    .map((s) => decodeURIComponent(String(s)).toLowerCase().trim());

  for (const key of candidates) {
    if (INJECTABLE_MONOGRAPHS[key]) {
      return INJECTABLE_MONOGRAPHS[key];
    }
    if (SIBLING_OVERRIDES[key]) {
      const { base, ...overrides } = SIBLING_OVERRIDES[key];
      return { ...(INJECTABLE_MONOGRAPHS[base] || {}), ...overrides };
    }
    if (INJECTABLE_ALIASES[key] && INJECTABLE_MONOGRAPHS[INJECTABLE_ALIASES[key]]) {
      return INJECTABLE_MONOGRAPHS[INJECTABLE_ALIASES[key]];
    }
  }

  return null;
}

