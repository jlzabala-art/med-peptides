export function computeTelstarPricing(listPriceEur, discountPct = 0.3) {
  if (listPriceEur == null || Number.isNaN(Number(listPriceEur)) || Number(listPriceEur) <= 0) {
    return {
      listPriceEur: null,
      distributorDiscountPct: discountPct,
      netTransferPriceEur: null,
      wholesalePriceEur: null,
      clinicPriceEur: null,
      retailPriceEur: null,
      onRequest: true,
    };
  }
  const list = Number(listPriceEur);
  const disc = Number(discountPct || 0);
  const net = Number((list * (1 - disc)).toFixed(2));
  const wholesale = disc > 0 ? Math.round(net * 1.15) : Math.round(list);
  const clinic = disc > 0 ? Math.round(list * 0.92) : Math.round(list);
  return {
    listPriceEur: list,
    distributorDiscountPct: disc,
    netTransferPriceEur: net,
    wholesalePriceEur: wholesale,
    clinicPriceEur: clinic,
    retailPriceEur: Math.round(list),
    onRequest: false,
  };
}

function item(sku, model, description, listPriceEur, discountPct = 0.3, extra = {}) {
  return {
    sku: String(sku),
    model,
    description,
    ...computeTelstarPricing(listPriceEur, discountPct),
    ...extra,
  };
}

