export function getAllTelstarEquipment() {
  return TELSTAR_2027_MODELS.map((m) => buildTelstarProductDocument(m));
}

export function getTelstarEquipmentBySlug(slug) {
  if (!slug) return null;
  const norm = String(slug).toLowerCase().trim();
  const model = TELSTAR_2027_MODELS.find(
    (m) => m.slug === norm || m.id === norm || String(m.sku).toLowerCase() === norm
  );
  return model ? buildTelstarProductDocument(model) : null;
}
