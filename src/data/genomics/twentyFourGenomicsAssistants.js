export const TWENTY_FOUR_GENOMICS_ASSISTANT_LIST = Object.values(TWENTY_FOUR_GENOMICS_ASSISTANTS);

export function getGenomicsAssistantByKey(key = 'skin-and-hair') {
  return TWENTY_FOUR_GENOMICS_ASSISTANTS[key] || TWENTY_FOUR_GENOMICS_ASSISTANTS['skin-and-hair'];
}

export function resolveAssistantKeyForPanel(panel = {}) {
  const hay = `${panel.id || ''} ${panel.sku || ''} ${panel.name || ''} ${panel.category || ''}`.toLowerCase();
  if (hay.includes('skin') || hay.includes('hair') || hay.includes('piel')) return 'skin-and-hair';
  if (hay.includes('nutri') || hay.includes('diet')) return 'nutritional';
  if (hay.includes('sport') || hay.includes('deport')) return 'sports';
  if (hay.includes('ancestr') || hay.includes('origin')) return 'ancestry';
  if (hay.includes('personal')) return 'personality';
  return null;
}
