export function getLocalizedField(product, field, lang = 'en') {
  if (!product) return '';
  const translations = product.aiContent?.translations?.[lang] || product.translations?.[lang] || {};
  return translations[field] || product[`${field}_${lang}`] || product[field] || '';
}

